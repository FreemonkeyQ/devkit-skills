#!/usr/bin/env python3
"""从各 SKILL.md 的 frontmatter 生成 dv-help 的总表。

用法：
  python3 scripts/dv-help-gen.py           # 写入 references/_generated.md
  python3 scripts/dv-help-gen.py --check   # 只校验是否漂移（CI 用）
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
OUT = SKILLS / "dv-help" / "references" / "_generated.md"

STAGE_ZH = {"meta": "元", "discover": "需求设计", "build": "实现", "verify": "验证", "ship": "交付"}


def parse(text: str) -> dict:
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---\n", 4)
    if end < 0:
        return {}
    raw = text[4:end]
    data: dict = {}
    cur = None
    for line in raw.splitlines():
        m = re.match(r"^(\s*)([A-Za-z0-9_-]+):\s*(.*)$", line)
        if not m:
            continue
        indent, key, val = len(m.group(1)), m.group(2), m.group(3).strip()
        if indent == 0:
            cur = key
            data[key] = val.strip('"').strip("'") if val else {}
        elif cur and isinstance(data.get(cur), dict):
            if val.startswith("[") and val.endswith("]"):
                data[cur][key] = [x.strip().strip('"').strip("'") for x in val[1:-1].split(",") if x.strip()]
            else:
                data[cur][key] = val.strip('"').strip("'")
    return data


def short_desc(desc: str) -> str:
    desc = re.sub(r"\s*Triggers:.*$", "", desc, flags=re.S).strip()
    return desc.split("。")[0][:40]


def build() -> str:
    rows = []
    for p in sorted(SKILLS.iterdir()):
        sm = p / "SKILL.md"
        if not sm.is_file():
            continue
        fm = parse(sm.read_text(encoding="utf-8"))
        meta = fm.get("metadata") or {}
        name = fm.get("name", p.name)
        auto = "自动" if name in {"dv-route", "dv-research", "dv-debug", "dv-review"} else "手动"
        nxt = meta.get("next")
        next_txt = "—" if nxt == [] else ("、".join(nxt) if isinstance(nxt, list) else "—")
        rows.append(
            f"| {name} | {STAGE_ZH.get(str(meta.get('stage')), str(meta.get('stage')))} | "
            f"{short_desc(str(fm.get('description', '')))} | {auto} | "
            f"{'是' if str(meta.get('edits-code')) == 'true' else '否'} | {next_txt} |"
        )
    head = (
        "<!-- GENERATED by scripts/dv-help-gen.py — 请勿手改 -->\n\n"
        "| 技能 | 阶段 | 作用 | 触发 | 改代码 | 下一步 |\n"
        "|---|---|---|---|:--:|---|\n"
    )
    return head + "\n".join(rows) + "\n"


def main() -> int:
    content = build()
    check = "--check" in sys.argv
    OUT.parent.mkdir(parents=True, exist_ok=True)
    if check:
        old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if old != content:
            print("ERROR dv-help 总表已漂移，请运行 python3 scripts/dv-help-gen.py")
            return 1
        print("OK 总表一致")
        return 0
    OUT.write_text(content, encoding="utf-8")
    print(f"written {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
